    "🔹 <b>Риски</b>\n"
    "Инвестиции в финансовые инструменты сопряжены с высоким риском потери "
    "капитала. Историческая доходность не гарантирует будущих результатов. "
    "AI-модель может допускать ошибки, данные могут задерживаться или быть "
    "неточными. Решения о финансовых операциях вы принимаете самостоятельно "
    "и несёте полную ответственность за все риски.\n\n"
    "🔹 <b>Ответственность</b>\n"
    "Разработчик бота не несёт ответственности за любые убытки или упущенную "
